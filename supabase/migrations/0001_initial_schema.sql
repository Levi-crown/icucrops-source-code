-- ICuCrops - initial Supabase (PostgreSQL) schema.
--
-- Ported from the union of the two stores that ran side by side under the
-- `hybrid` backend: the SQLite file (crops_db.sqlite) and the Firebase RTDB
-- export taken on 2026-08-20. Neither store on its own is complete - each
-- carried columns the other never had - so this file is the merge.
--
-- Timestamps stay `text` on purpose. Every value in both stores is already
-- ISO-8601 with an offset, which sorts correctly as text, and the backend
-- compares them as strings in ~160 places. Converting to timestamptz is a
-- separate migration, not a prerequisite for the cutover.

-- ---------------------------------------------------------------- accounts

CREATE TABLE users (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name             text    NOT NULL,
    email                    text    NOT NULL UNIQUE,
    role                     text    NOT NULL CHECK (role IN ('admin', 'user')),
    password_hash            text    NOT NULL,
    password_salt            text    NOT NULL,
    password_iterations      integer NOT NULL DEFAULT 310000,
    is_active                boolean NOT NULL DEFAULT true,
    -- SQLite-only until now: the Firebase records never carried these.
    preferences              jsonb   NOT NULL DEFAULT '{}'::jsonb,
    profile_photo_path       text    NOT NULL DEFAULT '',
    profile_photo_mime       text    NOT NULL DEFAULT '',
    profile_photo_data       bytea,
    profile_photo_version    text    NOT NULL DEFAULT '',
    -- Firebase-only until now. These three drive single-session enforcement;
    -- dropping them would silently disable it on the SQLite path.
    active_session_jti       text    NOT NULL DEFAULT '',
    active_session_client_id text    NOT NULL DEFAULT '',
    active_session_issued_at text    NOT NULL DEFAULT '',
    created_at               text    NOT NULL,
    updated_at               text    NOT NULL
);

-- Scoped by client address rather than by account, because most failed
-- sign-ins name an email that matches no user - which is exactly when a
-- lockout has to work. user_id is therefore nullable: it names the account
-- that was aimed at when the email did resolve, and stays NULL otherwise.
CREATE TABLE admin_login_attempts (
    scope_key     text    PRIMARY KEY,
    attempt_count integer NOT NULL DEFAULT 0,
    locked_until  text,
    user_id       bigint  REFERENCES users (id) ON DELETE SET NULL,
    updated_at    text    NOT NULL
);

CREATE INDEX admin_login_attempts_user_idx ON admin_login_attempts (user_id);

CREATE TABLE login_challenges (
    id             text    PRIMARY KEY,
    user_id        bigint  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    otp_hash       text    NOT NULL,
    otp_salt       text    NOT NULL,
    otp_iterations integer NOT NULL DEFAULT 120000,
    attempt_count  integer NOT NULL DEFAULT 0,
    max_attempts   integer NOT NULL DEFAULT 5,
    created_at     text    NOT NULL,
    expires_at     text    NOT NULL,
    consumed_at    text
);

CREATE TABLE account_creation_challenges (
    id                  text    PRIMARY KEY,
    display_name        text    NOT NULL,
    email               text    NOT NULL,
    role                text    NOT NULL CHECK (role IN ('admin', 'user')),
    password_hash       text    NOT NULL,
    password_salt       text    NOT NULL,
    password_iterations integer NOT NULL DEFAULT 310000,
    otp_hash            text    NOT NULL,
    otp_salt            text    NOT NULL,
    otp_iterations      integer NOT NULL DEFAULT 120000,
    attempt_count       integer NOT NULL DEFAULT 0,
    max_attempts        integer NOT NULL DEFAULT 5,
    created_at          text    NOT NULL,
    expires_at          text    NOT NULL,
    consumed_at         text,
    -- Set when the challenge is redeemed into a real account. Under the
    -- current purge policy the row is deleted at that moment - it carries a
    -- password hash and an OTP hash - so in practice this stays NULL. It is
    -- here so the relationship is declared rather than implied.
    created_user_id     bigint  REFERENCES users (id) ON DELETE SET NULL
);

CREATE INDEX login_challenges_user_idx ON login_challenges (user_id);
CREATE INDEX account_creation_challenges_email_idx ON account_creation_challenges (email);

-- ------------------------------------------------------------- cultivation

CREATE TABLE cultivations (
    id                 bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_key            text    NOT NULL UNIQUE CHECK (row_key IN ('row1', 'row2', 'row3', 'row4')),
    crop_type          text    NOT NULL,
    custom_plant_name  text    NOT NULL DEFAULT '',
    crop_name          text    NOT NULL,
    planting_date      text    NOT NULL,
    harvest_date       text    NOT NULL,
    days_to_harvest    integer NOT NULL,
    parameter_mode     text    NOT NULL CHECK (parameter_mode IN ('recommended', 'custom')),
    parameters_json    jsonb   NOT NULL,
    created_by_user_id bigint  REFERENCES users (id) ON DELETE SET NULL,
    created_at         text    NOT NULL,
    updated_at         text    NOT NULL
);

-- -------------------------------------------------------------- irrigation

CREATE TABLE irrigation_settings (
    channel_key         text    PRIMARY KEY,
    label               text    NOT NULL,
    automatic_duration_seconds integer NOT NULL DEFAULT 0,
    manual_duration_seconds    integer NOT NULL DEFAULT 0,
    schedule_start_time text    NOT NULL DEFAULT '06:00',
    schedule_duration_seconds  integer NOT NULL DEFAULT 0,
    schedule_frequency  text    NOT NULL DEFAULT 'daily',
    automatic_enabled   boolean NOT NULL DEFAULT true,
    schedule_enabled    boolean NOT NULL DEFAULT true,
    updated_at          text    NOT NULL
);

CREATE TABLE irrigation_row_controls (
    cultivation_id bigint  PRIMARY KEY REFERENCES cultivations (id) ON DELETE CASCADE,
    row_key        text    NOT NULL UNIQUE CHECK (row_key IN ('row1', 'row2', 'row3', 'row4')),
    mode           text    NOT NULL DEFAULT 'automatic' CHECK (mode IN ('automatic', 'schedule', 'manual')),
    is_enabled     boolean NOT NULL DEFAULT true,
    updated_at     text    NOT NULL
);

CREATE TABLE irrigation_row_settings (
    cultivation_id      bigint  NOT NULL REFERENCES cultivations (id) ON DELETE CASCADE,
    row_key             text    NOT NULL CHECK (row_key IN ('row1', 'row2', 'row3', 'row4')),
    channel_key         text    NOT NULL REFERENCES irrigation_settings (channel_key) ON DELETE CASCADE,
    automatic_enabled   boolean NOT NULL DEFAULT true,
    schedule_enabled    boolean NOT NULL DEFAULT true,
    automatic_duration_seconds integer NOT NULL DEFAULT 900,
    manual_duration_seconds    integer NOT NULL DEFAULT 900,
    schedule_start_time text    NOT NULL DEFAULT '06:00',
    schedule_duration_seconds  integer NOT NULL DEFAULT 1200,
    schedule_frequency  text    NOT NULL DEFAULT 'daily',
    updated_at          text    NOT NULL,
    PRIMARY KEY (cultivation_id, channel_key),
    UNIQUE (row_key, channel_key)
);

CREATE TABLE irrigation_runs (
    id                   bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT, not CASCADE: a channel that has run history behind it should
    -- not be deletable out from under that history.
    channel_key          text    NOT NULL REFERENCES irrigation_settings (channel_key) ON DELETE RESTRICT,
    mode                 text    NOT NULL,
    status               text    NOT NULL,
    duration_seconds     integer NOT NULL DEFAULT 0,
    started_at           text    NOT NULL,
    ended_at             text,
    requested_by_user_id bigint  REFERENCES users (id) ON DELETE SET NULL,
    notes                text    NOT NULL DEFAULT '',
    -- Firebase-only until now.
    target_rows          jsonb   NOT NULL DEFAULT '[]'::jsonb
);

CREATE TABLE irrigation_run_rows (
    irrigation_run_id bigint NOT NULL REFERENCES irrigation_runs (id) ON DELETE CASCADE,
    cultivation_id    bigint REFERENCES cultivations (id) ON DELETE SET NULL,
    row_key           text   NOT NULL CHECK (row_key IN ('row1', 'row2', 'row3', 'row4')),
    status            text   NOT NULL DEFAULT 'active',
    started_at        text   NOT NULL,
    ended_at          text,
    PRIMARY KEY (irrigation_run_id, row_key)
);

CREATE INDEX irrigation_runs_started_idx ON irrigation_runs (started_at DESC);
CREATE INDEX irrigation_run_rows_cultivation_idx ON irrigation_run_rows (cultivation_id);

-- ----------------------------------------------------------------- sensors

CREATE TABLE sensor_backends (
    id                         bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    backend_key                text    NOT NULL UNIQUE,
    display_name               text    NOT NULL,
    ingest_path                text    NOT NULL DEFAULT '',
    protocol                   text    NOT NULL DEFAULT 'http',
    source_type                text    NOT NULL DEFAULT 'api',
    hardware_identifier_prefix text    NOT NULL DEFAULT '',
    is_active                  boolean NOT NULL DEFAULT true,
    metadata_json              jsonb   NOT NULL DEFAULT '{}'::jsonb,
    created_at                 text    NOT NULL,
    updated_at                 text    NOT NULL
);

CREATE TABLE sensor_definitions (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    definition_key        text   NOT NULL UNIQUE,
    display_name          text   NOT NULL,
    category              text   NOT NULL DEFAULT 'sensor',
    default_device_name   text   NOT NULL DEFAULT '',
    default_row_key       text   NOT NULL DEFAULT '',
    default_power_state   text   NOT NULL DEFAULT 'on',
    default_actuator_mode text   NOT NULL DEFAULT '',
    metric_keys_json      jsonb  NOT NULL DEFAULT '[]'::jsonb,
    metadata_json         jsonb  NOT NULL DEFAULT '{}'::jsonb,
    created_at            text   NOT NULL,
    updated_at            text   NOT NULL
);

CREATE TABLE sensor_registry (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sensor_key          text   NOT NULL UNIQUE,
    display_name        text   NOT NULL,
    device_name         text   NOT NULL DEFAULT '',
    row_key             text   NOT NULL DEFAULT '',
    category            text   NOT NULL DEFAULT 'sensor',
    power_state         text   NOT NULL DEFAULT 'on',
    actuator_mode       text   NOT NULL DEFAULT '',
    alert_mode          text   NOT NULL DEFAULT '',
    hardware_identifier text   NOT NULL DEFAULT '',
    metric_keys_json    jsonb  NOT NULL DEFAULT '[]'::jsonb,
    metadata_json       jsonb  NOT NULL DEFAULT '{}'::jsonb,
    -- Added by ALTER TABLE in the SQLite era, so these arrived without
    -- foreign keys and defaulting to '' rather than NULL. They are real
    -- references now, which required '' -> NULL: a foreign key cannot point
    -- at an empty string. Every read of them in main.py is written
    -- str(row[...] or "") so a NULL reads back blank rather than "None".
    -- SET NULL, not CASCADE: retiring a definition should orphan the sensor,
    -- not delete it and its readings.
    definition_key      text   REFERENCES sensor_definitions (definition_key) ON DELETE SET NULL,
    backend_key         text   REFERENCES sensor_backends (backend_key) ON DELETE SET NULL,
    created_at          text   NOT NULL,
    updated_at          text   NOT NULL
);

-- `id` is text, not bigint, and that is load-bearing.
--
-- Of the 50,364 rows in the Firebase export, 43,748 (87%) carry an id the
-- Raspberry Pi minted for itself while offline, of the form `pi-<hex>`. Only
-- 6,616 came from the server-side counter. A bigint identity column cannot
-- hold the Pi ids at all - which is very likely why the local SQLite file,
-- whose sensor_readings.id is INTEGER, ended up with zero readings in it.
--
-- Offline id generation on the Pi is exactly the behaviour the sync design
-- depends on, so the column is typed to match it.
-- The default matters: SQLite handed out an id automatically through
-- AUTOINCREMENT, and every INSERT in main.py was written expecting that. A
-- text primary key generates nothing on its own, so without this the first
-- reading recorded fails on a not-null violation. The `srv-` prefix keeps
-- server-minted ids distinguishable from the Pi's `pi-` ones at a glance.
CREATE TABLE sensor_readings (
    id                   text  PRIMARY KEY
                               DEFAULT ('srv-' || replace(gen_random_uuid()::text, '-', '')),
    sensor_key           text  NOT NULL REFERENCES sensor_registry (sensor_key) ON DELETE CASCADE,
    reading_payload_json jsonb NOT NULL,
    source_type          text  NOT NULL DEFAULT 'seed',
    source_identifier    text  NOT NULL DEFAULT '',
    captured_at          text  NOT NULL
);

-- The dashboard always asks for one sensor recent history, newest first.
CREATE INDEX sensor_readings_sensor_captured_idx ON sensor_readings (sensor_key, captured_at DESC);
CREATE INDEX sensor_readings_captured_idx ON sensor_readings (captured_at DESC);

-- Replaces the hand-maintained Firebase `sensor_latest` mirror node.
CREATE VIEW sensor_latest WITH (security_invoker = true) AS
SELECT DISTINCT ON (sensor_key) *
FROM sensor_readings
ORDER BY sensor_key, captured_at DESC;

-- ----------------------------------------------------------- notifications

CREATE TABLE notifications (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scope       text   NOT NULL CHECK (scope IN ('all', 'admin', 'user')),
    type        text   NOT NULL,
    message     text   NOT NULL,
    source_type text   NOT NULL DEFAULT '',
    source_id   text   NOT NULL DEFAULT '',
    created_at  text   NOT NULL,
    -- Deleting marks rather than removes, so the deletion itself can be
    -- carried to the other device. A row that is simply gone is
    -- indistinguishable from one that never arrived, and the sync would put
    -- it straight back. The row is removed for real by the sync's purge once
    -- the mark is old enough that both sides have seen it.
    deleted_at  text,
    -- The sync identifies a notification by these six fields rather than by
    -- id, because the two id sequences drifted apart. Making that key unique
    -- is what stops two overlapping runs - a timer firing into a manual one -
    -- from each deciding the other side is missing the row and both inserting.
    UNIQUE (scope, type, message, source_type, source_id, created_at)
);

CREATE INDEX notifications_deleted_idx ON notifications (deleted_at);

CREATE TABLE notification_reads (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notification_id bigint NOT NULL REFERENCES notifications (id) ON DELETE CASCADE,
    user_id         bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    read_at         text   NOT NULL,
    UNIQUE (notification_id, user_id)
);

CREATE INDEX notifications_created_idx ON notifications (created_at DESC);
CREATE INDEX notification_reads_user_idx ON notification_reads (user_id);

-- ------------------------------------------------------------------ system

-- Also the new home for the Firebase `_meta` leaves that outlive the
-- migration: realtime_versions (polled by assets/realtime-sync.js) and
-- otp_email_relay (the Pi relay heartbeat). The `_meta/counters` node does
-- not come across - identity sequences replace it.
CREATE TABLE system_state (
    state_key          text   PRIMARY KEY,
    state_value        text   NOT NULL,
    -- Who last changed the setting. NULL for the many writes that come from
    -- the irrigation and environment workers rather than from a person.
    updated_by_user_id bigint REFERENCES users (id) ON DELETE SET NULL,
    updated_at         text   NOT NULL
);

-- --------------------------------------------------------------------- RLS
--
-- The backend connects as a privileged role and bypasses RLS entirely, so
-- these do not affect it. They exist so that if a Supabase anon key is ever
-- put in front of this project - by a later change, or by accident - every
-- table refuses to answer. Enabled with no policies attached means deny-all.
-- This is the guard that was missing on Firebase.

ALTER TABLE users                       ENABLE ROW LEVEL SECURITY;
ALTER TABLE admin_login_attempts        ENABLE ROW LEVEL SECURITY;
ALTER TABLE login_challenges            ENABLE ROW LEVEL SECURITY;
ALTER TABLE account_creation_challenges ENABLE ROW LEVEL SECURITY;
ALTER TABLE cultivations                ENABLE ROW LEVEL SECURITY;
ALTER TABLE irrigation_settings         ENABLE ROW LEVEL SECURITY;
ALTER TABLE irrigation_row_controls     ENABLE ROW LEVEL SECURITY;
ALTER TABLE irrigation_row_settings     ENABLE ROW LEVEL SECURITY;
ALTER TABLE irrigation_runs             ENABLE ROW LEVEL SECURITY;
ALTER TABLE irrigation_run_rows         ENABLE ROW LEVEL SECURITY;
ALTER TABLE sensor_backends             ENABLE ROW LEVEL SECURITY;
ALTER TABLE sensor_definitions          ENABLE ROW LEVEL SECURITY;
ALTER TABLE sensor_registry             ENABLE ROW LEVEL SECURITY;
ALTER TABLE sensor_readings             ENABLE ROW LEVEL SECURITY;
ALTER TABLE notifications               ENABLE ROW LEVEL SECURITY;
ALTER TABLE notification_reads          ENABLE ROW LEVEL SECURITY;
ALTER TABLE system_state                ENABLE ROW LEVEL SECURITY;
