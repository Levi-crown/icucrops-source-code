-- What actually came out of each row, kept after the row is replanted.
--
-- Until now a finished crop could only be deleted, so the farm lost the record
-- of what it grew and the Reports page had nothing to say about completed
-- cycles. Marking a cultivation harvested moves it here.
--
-- This cannot be a status column on cultivations, for the same reason
-- 0003_sync_tombstones.sql could not put its mark on the row: cultivations
-- .row_key is UNIQUE, so a finished crop left in place would sit in the slot
-- and block the next planting. A harvest is a different kind of record anyway
-- -- append-only history rather than current state, owning no slot -- so it
-- gets its own table with no UNIQUE row_key at all.
--
-- days_grown and on_schedule are derived once, when the harvest is recorded,
-- and stored rather than computed on read. Computing them later needs "today",
-- which is not stable across a re-run of the same report: the same export
-- would answer differently tomorrow. parameters_json is copied for the same
-- reason -- the record has to stay readable after its cultivation is gone.
--
-- created_at carries the *cultivation's* created_at, not this row's. That is
-- what the sync hashes into 'row1|<created_at>', so keeping it lets a harvest
-- be matched to the tombstone that removed the cultivation it came from.
--
-- on_schedule is boolean here and INTEGER on SQLite, which is the same split
-- users.is_active already has; the sync converts at the boundary. Writing a
-- bare 1 into this column from the Pi's side would throw on Postgres only.

CREATE TABLE IF NOT EXISTS cultivation_harvests (
    id                   bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_key              text    NOT NULL CHECK (row_key IN ('row1', 'row2', 'row3', 'row4')),
    crop_type            text    NOT NULL,
    custom_plant_name    text    NOT NULL DEFAULT '',
    crop_name            text    NOT NULL,
    planting_date        text    NOT NULL,
    harvest_date         text    NOT NULL,
    days_to_harvest      integer NOT NULL,
    parameter_mode       text    NOT NULL,
    parameters_json      jsonb   NOT NULL,
    harvested_at         text    NOT NULL,
    days_grown           integer NOT NULL DEFAULT 0,
    on_schedule          boolean NOT NULL DEFAULT true,
    planted_by_user_id   bigint  REFERENCES users (id) ON DELETE SET NULL,
    harvested_by_user_id bigint  REFERENCES users (id) ON DELETE SET NULL,
    created_at           text    NOT NULL,
    -- The natural key both transports use. The farm's uplink blocks the
    -- Postgres port, so a harvest may arrive here over the HTTPS relay and
    -- again later over the ordinary sync; neither has a durable ack. This is
    -- what makes replaying either pass a no-op instead of a duplicate.
    UNIQUE (row_key, planting_date, harvested_at)
);

-- Reports window on harvested_at, newest first.
CREATE INDEX IF NOT EXISTS cultivation_harvests_harvested_idx
    ON cultivation_harvests (harvested_at DESC);

-- Same wake-up as the other tables the Pi mirrors.
DROP TRIGGER IF EXISTS cultivation_harvests_edge_sync ON cultivation_harvests;
CREATE TRIGGER cultivation_harvests_edge_sync
AFTER INSERT OR UPDATE OR DELETE ON cultivation_harvests
FOR EACH STATEMENT EXECUTE FUNCTION icucrops_notify_edge_sync();
