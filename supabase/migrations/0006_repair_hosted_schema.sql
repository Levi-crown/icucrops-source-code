-- ICuCrops: bring Supabase up to the schema the deployed code expects.
--
-- Run this once in the Supabase SQL Editor (Dashboard -> SQL Editor -> New
-- query -> paste -> Run). It is safe to run more than once: every step checks
-- the current state first, so a column that was already renamed is left alone
-- and no value is ever multiplied by 60 twice.
--
-- Why this is needed: commit b5a7ed3 moved every irrigation duration from
-- minutes to seconds and renamed the columns. SQLite migrates itself on the
-- Pi, which is why the Pi kept working. Supabase owns its schema through
-- supabase/migrations/ and nothing applies those automatically, so the hosted
-- site was left querying columns that do not exist:
--
--   UndefinedColumn: column "duration_seconds" does not exist
--
-- That one error broke three things at once on Vercel: the Irrigation page
-- ("No active cultivation row"), the Reports page ("The farm database is not
-- reachable"), and POST /api/hardware/sync -- which 500'd every relay pass, so
-- readings stopped landing and the badge fell to Offline.

BEGIN;

-- ---------------------------------------------------------------------------
-- 0004: the harvests table, which was never committed or applied.
-- Already idempotent; included so a harvest or a report cannot fail later.
-- ---------------------------------------------------------------------------

CREATE TABLE IF NOT EXISTS cultivation_harvests (
    id                   bigint  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    row_key              text    NOT NULL CHECK (row_key IN ('row1', 'row2', 'row3', 'row4')),
    crop_type            text    NOT NULL,
    custom_plant_name    text    NOT NULL DEFAULT '',
    crop_name            text    NOT NULL,
    planting_date        text    NOT NULL,
    harvest_date         text    NOT NULL,
    days_to_harvest      integer NOT NULL,
    parameter_mode       text    NOT NULL,
    parameters_json      jsonb   NOT NULL,
    harvested_at         text    NOT NULL,
    days_grown           integer NOT NULL DEFAULT 0,
    on_schedule          boolean NOT NULL DEFAULT true,
    planted_by_user_id   bigint  REFERENCES users (id) ON DELETE SET NULL,
    harvested_by_user_id bigint  REFERENCES users (id) ON DELETE SET NULL,
    created_at           text    NOT NULL,
    UNIQUE (row_key, planting_date, harvested_at)
);

CREATE INDEX IF NOT EXISTS cultivation_harvests_harvested_idx
    ON cultivation_harvests (harvested_at DESC);

DROP TRIGGER IF EXISTS cultivation_harvests_edge_sync ON cultivation_harvests;
CREATE TRIGGER cultivation_harvests_edge_sync
AFTER INSERT OR UPDATE OR DELETE ON cultivation_harvests
FOR EACH STATEMENT EXECUTE FUNCTION icucrops_notify_edge_sync();

-- ---------------------------------------------------------------------------
-- 0005: irrigation durations become seconds.
--
-- The rename and the *60 are bound together in one guarded block per column:
-- the values are only multiplied in the same branch that does the rename, so
-- a column already carrying seconds is never scaled again.
-- ---------------------------------------------------------------------------

DO $$
DECLARE
    target record;
BEGIN
    FOR target IN
        SELECT * FROM (VALUES
            ('irrigation_settings',     'automatic_duration', 'automatic_duration_seconds'),
            ('irrigation_settings',     'manual_duration',    'manual_duration_seconds'),
            ('irrigation_settings',     'schedule_duration',  'schedule_duration_seconds'),
            ('irrigation_row_settings', 'automatic_duration', 'automatic_duration_seconds'),
            ('irrigation_row_settings', 'manual_duration',    'manual_duration_seconds'),
            ('irrigation_row_settings', 'schedule_duration',  'schedule_duration_seconds'),
            ('irrigation_runs',         'duration_minutes',   'duration_seconds')
        ) AS t(table_name, old_column, new_column)
    LOOP
        -- Only act when the old name is still there AND the new one is not.
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public'
               AND table_name   = target.table_name
               AND column_name  = target.old_column
        ) AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
             WHERE table_schema = 'public'
               AND table_name   = target.table_name
               AND column_name  = target.new_column
        ) THEN
            EXECUTE format(
                'ALTER TABLE public.%I RENAME COLUMN %I TO %I',
                target.table_name, target.old_column, target.new_column
            );
            -- Same branch as the rename, so this runs exactly once, ever.
            EXECUTE format(
                'UPDATE public.%I SET %I = %I * 60',
                target.table_name, target.new_column, target.new_column
            );
            RAISE NOTICE 'renamed %.% -> % and converted to seconds',
                target.table_name, target.old_column, target.new_column;
        END IF;
    END LOOP;
END $$;

-- Defaults, stated in seconds. Setting a default is naturally idempotent.
ALTER TABLE irrigation_row_settings
    ALTER COLUMN automatic_duration_seconds SET DEFAULT 900;
ALTER TABLE irrigation_row_settings
    ALTER COLUMN manual_duration_seconds SET DEFAULT 900;
ALTER TABLE irrigation_row_settings
    ALTER COLUMN schedule_duration_seconds SET DEFAULT 1200;

COMMIT;

-- ---------------------------------------------------------------------------
-- Verification. Every row should read ok = true.
-- ---------------------------------------------------------------------------

SELECT
    'irrigation_settings.automatic_duration_seconds' AS column_checked,
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_settings'
               AND column_name='automatic_duration_seconds') AS ok
UNION ALL SELECT 'irrigation_settings.manual_duration_seconds',
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_settings'
               AND column_name='manual_duration_seconds')
UNION ALL SELECT 'irrigation_settings.schedule_duration_seconds',
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_settings'
               AND column_name='schedule_duration_seconds')
UNION ALL SELECT 'irrigation_row_settings.automatic_duration_seconds',
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_row_settings'
               AND column_name='automatic_duration_seconds')
UNION ALL SELECT 'irrigation_row_settings.manual_duration_seconds',
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_row_settings'
               AND column_name='manual_duration_seconds')
UNION ALL SELECT 'irrigation_row_settings.schedule_duration_seconds',
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_row_settings'
               AND column_name='schedule_duration_seconds')
UNION ALL SELECT 'irrigation_runs.duration_seconds',
    EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public' AND table_name='irrigation_runs'
               AND column_name='duration_seconds')
UNION ALL SELECT 'cultivation_harvests table',
    EXISTS (SELECT 1 FROM information_schema.tables
             WHERE table_schema='public' AND table_name='cultivation_harvests')
UNION ALL SELECT 'no stale *_minutes / *_duration columns remain',
    NOT EXISTS (SELECT 1 FROM information_schema.columns
             WHERE table_schema='public'
               AND table_name IN ('irrigation_settings','irrigation_row_settings','irrigation_runs')
               AND (column_name LIKE '%\_minutes' OR column_name IN
                    ('automatic_duration','manual_duration','schedule_duration')));
